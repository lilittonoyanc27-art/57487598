// Helper to normalize input: strips accents, lowercases, trims
export function normalizeText(text: string): string {
  return text
    .toLowerCase()
    .trim()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '') // remove accent marks
    .replace(/[^a-zñ0-9]/g, '');
}

export function checkAnswer(userInput: string, question: PasapalabraQuestion): boolean {
  const normUser = normalizeText(userInput);
  if (!normUser) return false;

  // Exact or normalized check
  const userClean = userInput.trim().toLowerCase();
  for (const accepted of question.acceptedAnswers) {
    if (userClean === accepted.toLowerCase()) return true;
    if (normUser === normalizeText(accepted)) return true;
    // Also allow without 'el'/'la'
    if (normUser === normalizeText(accepted.replace(/^(el|la|los|las)\s+/, ''))) return true;
  }

  // Also check direct wordEs
  if (normUser === normalizeText(question.wordEs)) return true;

  return false;
}
